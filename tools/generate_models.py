GENERATED_MARK = "GENERATED by tools/generate_models.py"


class GenerationError(ValueError):
    """A body the generator refuses (Jinja delimiter, unknown :param, header/body drift, a
    source outside sources.yml, a hand-written file in the way). Never swallowed."""


# ---------------------------------------------------------------------------------------------
# body preparation
# ---------------------------------------------------------------------------------------------

_JINJA_DELIMS = ("{{", "}}", "{%", "%}", "{#", "#}")
_STARTS_RE = re.compile(r"^\s*(SELECT|WITH)\b", re.IGNORECASE)
_WINDOW_DAYS_RE = re.compile(r"\bwindow_days\b", re.IGNORECASE)
_PARAM_LEFTOVER_RE = re.compile(r"(?<![:\w]):([a-z_][a-z0-9_]*)\b")


def runner_body(body: str) -> str:
    """The public runner's own body: every line starting with `--` dropped (the header, and any
    column-0 comment line inside the body), stripped, trailing `;` removed."""
    text = "\n".join(line for line in body.splitlines() if not line.startswith("--"))
    return text.strip().rstrip(";").rstrip()


def guard_body(query_id: str, body: str) -> None:
    if not _STARTS_RE.match(body):
        raise GenerationError(f"{query_id}: body does not start with SELECT/WITH")
    for d in _JINJA_DELIMS:
        if d in body:
            raise GenerationError(
                f"{query_id}: body contains the Jinja delimiter {d!r}; it cannot be emitted as a "
                "dbt model without escaping"
            )
    if _WINDOW_DAYS_RE.search(mask(body)):
        raise GenerationError(f"{query_id}: body already names a column window_days")


# The settings query_source tag, filled by dbt (var) locally and by the export at run time.
QUERY_SOURCE_MARKER = "__QUERY_SOURCE__"
QUERY_SOURCE_DEFAULT = "Crosshire"


def tokenise_params(query_id: str, body: str, params: list[dict]) -> str:
    """`:period_days` -> `__W__`, other known `:name` -> `__P__name__` (longest name first, the
    runner's alternation, substituted everywhere exactly as resolve_sql() does). Any `:name` still
    present outside a literal/comment afterwards is an unknown param -> GenerationError."""
    known = sorted({p["name"] for p in params}, key=len, reverse=True)
    if known:
        pat = re.compile(r":(" + "|".join(re.escape(k) for k in known) + r")\b")
        body = pat.sub(
            lambda m: "__W__" if m.group(1) == "period_days" else f"__P__{m.group(1)}__", body
        )
    left = sorted({m.group(1) for m in _PARAM_LEFTOVER_RE.finditer(mask(body))})
    if left:
        raise GenerationError(
            f"{query_id}: unknown :param token(s) {left} -- not declared in the header's params"
        )
    return body.replace(QUERY_SOURCE_MARKER, f"{{{{ var('query_source', '{QUERY_SOURCE_DEFAULT}') }}}}")


_SOURCE_RE = re.compile(r"(?<![\w.`])system\.([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\b")

# These ids need the raw, non-deduplicated list_prices join (cost_chargeback_reconcile's
# price_join_fanout check compares it against a de-duplicated total; the *_raw ids collect the
# table as-is) -- every other reader gets {{ list_prices() }} instead of a plain source() call.
RAW_LIST_PRICES_IDS = frozenset({
    "cost_chargeback_reconcile",
    "overview_list_prices_raw",
    "pricing_list_prices_raw",
    "cost_account_prices_raw",
})

_ALIAS_STOP_WORDS = frozenset({
    "where", "group", "order", "union", "left", "right", "inner", "full", "cross",
    "join", "having", "limit", "qualify", "on",
})


def _needs_list_prices_alias(rest: str) -> bool:
    """After a bare `system.billing.list_prices` reference: true when no alias follows it directly
    (a line break, ')', ',' or a keyword), so the {{ list_prices() }} subquery that replaces it
    needs its own alias to stay valid SQL on both engines."""
    stripped = rest.lstrip(" \t")
    if stripped[:1] in ("", ")", ",", "\n"):
        return True
    word = re.match(r"[A-Za-z_][A-Za-z0-9_]*", stripped)
    return not word or word.group(0).lower() in _ALIAS_STOP_WORDS


def load_source_contract(sources_yml: Path = SOURCES_YML) -> dict[str, set[str]]:
    """{schema: {table, ...}} from dbt/models/sources/sources.yml (source name `system_<schema>`)."""
    doc = yaml.safe_load(sources_yml.read_text(encoding="utf-8"))
    contract: dict[str, set[str]] = {}
    for src in doc.get("sources", []):
        name = src["name"]
        schema = src.get("schema") or name.removeprefix("system_")
        if name != f"system_{schema}":
            raise GenerationError(f"sources.yml: source {name!r} does not follow system_<schema>")
        contract[schema] = {t["name"] for t in src.get("tables", [])}
    return contract


def substitute_sources(
    query_id: str, body: str, contract: dict[str, set[str]]
) -> tuple[str, list[tuple[str, str]]]:
    """`system.<s>.<t>` -> `{{ source('system_<s>', '<t>') }}` outside literals and comments.
    Returns the rewritten text and the (schema, table) pairs found, in order of first use."""
    m_text = mask(body)
    out: list[str] = []
    last = 0
    pairs: list[tuple[str, str]] = []
    for m in _SOURCE_RE.finditer(m_text):
        schema, table = m.group(1), m.group(2)
        if schema not in contract:
            raise GenerationError(f"{query_id}: system.{schema}.{table} -- schema not in sources.yml")
        if table not in contract[schema]:
            raise GenerationError(
                f"{query_id}: system.{schema}.{table} -- table not in sources.yml under system_{schema}"
            )
        if (schema, table) not in pairs:
            pairs.append((schema, table))
        out.append(body[last:m.start()])
        if (schema, table) == ("billing", "list_prices") and query_id not in RAW_LIST_PRICES_IDS:
            call = "{{ list_prices() }}"
            if _needs_list_prices_alias(body[m.end():]):
                call += " list_prices"
            out.append(call)
        else:
            out.append(f"{{{{ source('system_{schema}', '{table}') }}}}")
        last = m.end()
    out.append(body[last:])
    return "".join(out), pairs


def reads_drift(spec: QuerySpec) -> tuple[list[str], list[str]]:
    """(header_only, body_only): `system.<s>.<t>` pairs the header's `reads:` names but the body
    never reads, and pairs the body reads but the header omits. Both empty = no drift."""
    m_text = mask(runner_body(spec.body))
    found = {(m.group(1), m.group(2)) for m in _SOURCE_RE.finditer(m_text)}
    header = {tuple(p) for p in spec.sources}
    fmt = lambda pairs: sorted(f"system.{s}.{t}" for s, t in pairs)  # noqa: E731
    return fmt(header - found), fmt(found - header)


_W_RE = re.compile(r"\b__W__\b")
_P_RE = re.compile(r"\b__P__(\w+?)__(?!\w)")


def _literal(value) -> str:
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def expand_sentinels(query_id: str, text: str, params: list[dict]) -> str:
    defaults = {p["name"]: p["default"] for p in params}

    def rep(m: re.Match) -> str:
        name = m.group(1)
        if name not in defaults:
            raise GenerationError(f"{query_id}: sentinel __P__{name}__ has no header default")
        return f"{{{{ param('{query_id}', '{name}', {_literal(defaults[name])}) }}}}"

    text = _W_RE.sub("{{ w }}", text)
    return _P_RE.sub(rep, text)


# ---------------------------------------------------------------------------------------------
# meta extraction (order_by, limit)
# ---------------------------------------------------------------------------------------------

_ORDER_BY_RE = re.compile(r"\bORDER\s+BY\b", re.IGNORECASE)
_LIMIT_RE = re.compile(r"\bLIMIT\b", re.IGNORECASE)


def _depth_at(m_text: str) -> list[int]:
    """Parenthesis depth before each character of a masked string."""
    depths = []
    d = 0
    for ch in m_text:
        depths.append(d)
        if ch == "(":
            d += 1
        elif ch == ")":
            d -= 1
    return depths


def _top_level_tail(body: str, keyword: re.Pattern) -> tuple[int, int] | None:
    """(start, end) of the text after the LAST depth-0 occurrence of `keyword`, up to the next
    depth-0 LIMIT (when keyword is ORDER BY) or the end of the body."""
    m_text = mask(body)
    depths = _depth_at(m_text)
    hits = [m for m in keyword.finditer(m_text) if depths[m.start()] == 0]
    if not hits:
        return None
    start = hits[-1].end()
    end = len(body)
    if keyword is _ORDER_BY_RE:
        for m in _LIMIT_RE.finditer(m_text, start):
            if depths[m.start()] == 0:
                end = m.start()
                break
    return start, end


def _clean_clause(text: str) -> str:
    return " ".join(strip_comments(text).split())


def extract_order_by(body: str) -> str:
    """The text after the body's final top-level ORDER BY (the subaudit build_sql.py recipe,
    made parenthesis-aware), comments removed, whitespace collapsed; "" when there is none."""
    span = _top_level_tail(body, _ORDER_BY_RE)
    if span is None:
        return ""
    return _clean_clause(body[span[0]:span[1]])


def extract_limit(body: str) -> str:
    """The text after the body's final top-level LIMIT; "" when there is none."""
    span = _top_level_tail(body, _LIMIT_RE)
    if span is None:
        return ""
    return _clean_clause(body[span[0]:span[1]])


