#!/usr/bin/env python3
"""tools/generate_models.py -- vendored / app-owned queries -> dbt models (PLAN.md section 5.3).

    python tools/generate_models.py                       every executable query (113 today: 100 vendored + 13 app-owned)
    python tools/generate_models.py --only <id> [<id>..]  just those query ids
    python tools/generate_models.py --domain <name>       just that domain
    python tools/generate_models.py --check [scope]       exit 1 listing stale / missing / extra files
    python tools/generate_models.py --force               overwrite a model / yml file that lacks
                                                          the GENERATED marker (a hand-written file
                                                          in the way is otherwise refused)

Per executable query (registry `executable` flag; the DESCRIBE/ANALYZE templates are skipped
with a reason and listed under `skipped` in generated_manifest.json):

  1. body     = QuerySpec.body with every line starting with `--` dropped, trailing `;` removed --
                exactly the public runner's tools/run_audit.py resolve_sql() stripping rule.
                Guard: the body must start with SELECT/WITH, must not contain a Jinja delimiter
                and must not name a column `window_days`.
  2. tokens   = `:period_days` -> `__W__`, any other param the header declares -> `__P__<name>__`
                (longest-name-first alternation, the runner's own rule, so `':00'` in a time
                literal is untouched); any other `:name` outside a literal/comment is an error.
  2b. tokens  = app.core.translate.strip_resource_mask(tokens) then .mask_user_identities(tokens):
                a resource-name preview CASE -> the plain column; an identity-mask CASE -> one
                `{{ mask_user(...) }}` macro call, so both branches below mask the same way.
  3. duckdb   = app.core.translate.translate(tokens)   (PLAN.md 5.4 rule table, ends with the
                as-of pinning current_date() -> {{ audit_today() }} etc.)
     databricks = app.core.translate.pin_time(tokens)  (ONLY that same pinning; otherwise the
                runner's text, verbatim -- the library's copy-paste promise)
  4. both branches: `system.<s>.<t>` -> `{{ source('system_<s>', '<t>') }}` outside literals and
                comments, validated against dbt/models/sources/sources.yml; the pairs found must
                equal the header's `reads:` (header/body drift is an error, never silent).
  5. both branches: `__W__` -> `{{ w }}`, `__P__x__` -> `{{ param('<qid>', 'x', <default>) }}`.
  6. model text: one `SELECT {{ w }} AS window_days, q.* FROM (...) q` block per window joined by
                UNION ALL (windowed queries), or one `SELECT 0 AS window_days ...` block (no loop).

Outputs (LF, byte-identical on rerun, no timestamps):
  dbt/models/findings/<domain>/f_<query_id>.sql
  dbt/models/findings/<domain>/_findings__<domain>.yml    (all models present in that domain)
  dbt/models/findings/generated_manifest.json             (models written, skipped + reason, lock commit)

DEC-13: the three DRILLDOWN_IDS get the extra dbt tag `drilldown` (an explicit allowlist).
DEC-24: config/grains/*.yml list a query's own key columns; `window_days` is prepended here.
"""
