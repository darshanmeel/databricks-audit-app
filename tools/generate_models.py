def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    scope = ap.add_mutually_exclusive_group()
    scope.add_argument("--only", nargs="+", metavar="ID", help="only these query ids")
    scope.add_argument("--domain", metavar="NAME", help="only this domain")
    ap.add_argument("--check", action="store_true", help="verify, do not write; exit 1 on any drift")
    ap.add_argument("--force", action="store_true", help="overwrite files lacking the GENERATED marker")
    args = ap.parse_args(argv)
    try:
        if args.check:
            r = check(args.only, args.domain)
            for s in r["skipped"]:
                print(f"skipped: {s['query_id']} - {s['reason']}")
            for p in r["stale"]:
                print(f"stale: {p}")
            for p in r["missing"]:
                print(f"missing: {p}")
            for p in r["extra"]:
                print(f"extra: {p}")
            if r["ok"]:
                print(f"models in sync ({r['models']} models, {len(r['skipped'])} skipped)")
                return 0
            print(
                f"models out of sync: {len(r['stale'])} stale, {len(r['missing'])} missing, "
                f"{len(r['extra'])} extra -- rerun python tools/generate_models.py",
                file=sys.stderr,
            )
            return 1
        r = generate(args.only, args.domain, force=args.force)
        for s in r["skipped"]:
            print(f"skipped: {s['query_id']} - {s['reason']}")
        n_y = len(r["ymls"])
        print(f"wrote {len(r['models'])} models, {n_y} yml{'s' if n_y != 1 else ''}, {MANIFEST_NAME}")
        return 0
    except GenerationError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
