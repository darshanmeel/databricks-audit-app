def skip_reason(spec: QuerySpec) -> str | None:
    if spec.executable:
        return None
    if not spec.runnable:
        return "runnable: false (a DESCRIBE/ANALYZE template, not a SELECT)"
    return "reads no system table (" + (spec.reads[0] if spec.reads else "reads empty") + ")"


def model_name(spec: QuerySpec) -> str:
    return f"f_{spec.query_id}"


def model_tags(spec: QuerySpec) -> list[str]:
    tags = ["finding" if spec.is_finding else "inventory", f"domain:{spec.domain}", f"tier:{spec.tier}"]
    if spec.stars:
        tags.append("stars")
    if spec.query_id in DRILLDOWN_IDS:
        tags.append("drilldown")
    return tags


def render_branches(spec: QuerySpec, contract: dict[str, set[str]] | None = None) -> dict[str, str]:
    """{'duckdb': ..., 'databricks': ...}: the two derived-table bodies, fully substituted."""
    if not spec.executable:
        raise GenerationError(f"{spec.query_id}: not executable ({skip_reason(spec)})")
    contract = contract if contract is not None else load_source_contract()
    body = runner_body(spec.body)
    guard_body(spec.query_id, body)
    tokens = tokenise_params(spec.query_id, body, spec.params)
    # A resource-name preview -> the plain column, an identity mask -> the mask_user() macro call
    # -- before translate()/pin_time() so both branches get the identical rewrite.
    tokens = strip_resource_mask(tokens)
    tokens = mask_user_identities(tokens)
    try:
        duck = translate(tokens)
    except Untranslatable as e:
        raise GenerationError(f"{spec.query_id}: {e}") from e
    dbx = pin_time(tokens)
    duck, _ = substitute_sources(spec.query_id, duck, contract)
    dbx, pairs = substitute_sources(spec.query_id, dbx, contract)
    header_only, body_only = reads_drift(spec)
    if header_only or body_only:
        raise GenerationError(
            f"{spec.query_id}: header/body drift -- reads: names {header_only} the body never "
            f"reads; the body reads {body_only} the header omits"
        )
    return {
        "duckdb": expand_sentinels(spec.query_id, duck, spec.params),
        "databricks": expand_sentinels(spec.query_id, dbx, spec.params),
    }


def _origin_note(spec: QuerySpec, lock_commit: str) -> str:
    if spec.origin == "vendored":
        return f"{spec.path} (vendored @ {lock_commit})"
    return f"{spec.path} (app-owned)"


def render_model(
    spec: QuerySpec,
    target: str = "both",
    *,
    lock_commit: str | None = None,
    contract: dict[str, set[str]] | None = None,
) -> str:
    """The dbt model text (PLAN.md 5.3). target='both' emits the `{% if target.type == 'duckdb' %}`
    dual-branch model the CLI writes; 'duckdb' / 'databricks' emit a single-branch variant of the
    same shape (for tests that inspect one dialect without a Jinja render)."""
    if target not in ("both", "duckdb", "databricks"):
        raise ValueError(f"target must be both|duckdb|databricks, got {target!r}")
    branches = render_branches(spec, contract)
    commit = lock_commit if lock_commit is not None else load_lock_commit()
    tags = ", ".join(f"'{t}'" for t in model_tags(spec))
    if target == "both":
        inner = (
            "{%- if target.type == 'duckdb' %}\n"
            + branches["duckdb"]
            + "\n{%- else %}\n"
            + branches["databricks"]
            + "\n{%- endif %}"
        )
    else:
        inner = branches[target]
    head = (
        f"{{{{ config(materialized='table', tags=[{tags}]) }}}}\n"
        f"-- {GENERATED_MARK} from {_origin_note(spec, commit)}. Do not edit.\n"
    )
    if spec.windowed:
        return (
            head
            + "{%- set windows = var('windows', [7, 30, 90]) %}\n"
            "{%- for w in windows %}\n"
            "SELECT {{ w }} AS window_days, q.*\n"
            "FROM (\n"
            + inner
            + "\n) q\n"
            "{%- if not loop.last %}\n"
            "UNION ALL\n"
            "{%- endif %}\n"
            "{%- endfor %}\n"
        )
    return head + "SELECT 0 AS window_days, q.*\nFROM (\n" + inner + "\n) q\n"


def load_grains(grains_dir: Path = GRAINS_DIR) -> dict[str, list[str]]:
    """{query_id: [own key columns]} from every config/grains/*.yml (each file is a mapping
    query_id -> list of column names). An id named in two files is an error."""
    grains: dict[str, list[str]] = {}
    owner: dict[str, str] = {}
    if not grains_dir.exists():
        return grains
    for path in sorted(grains_dir.glob("*.yml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not isinstance(doc, dict):
            raise GenerationError(f"{path}: expected a mapping query_id -> [columns]")
        for qid, cols in doc.items():
            if isinstance(cols, dict):
                cols = cols.get("columns")
            if not isinstance(cols, list) or not cols or not all(isinstance(c, str) for c in cols):
                raise GenerationError(f"{path}: grain for {qid!r} must be a non-empty list of column names")
            if "window_days" in cols:
                raise GenerationError(f"{path}: grain for {qid!r} must not list window_days (DEC-24)")
            if qid in grains:
                raise GenerationError(f"grain for {qid!r} is defined in both {owner[qid]} and {path.name}")
            grains[qid] = list(cols)
            owner[qid] = path.name
    return grains


def load_lock_commit(lock_path: Path = LOCK_PATH) -> str:
    return str(json.loads(lock_path.read_text(encoding="utf-8"))["commit"])


def _limit_note(spec: QuerySpec, body: str) -> str:
    limit = extract_limit(body)
    if not limit:
        return ""
    defaults = {p["name"]: p["default"] for p in spec.params}
    m = re.fullmatch(r":([a-z_][a-z0-9_]*)", limit)
    if m and m.group(1) in defaults:
        return (f" Rows are capped inside every window_days block by the body's LIMIT :{m.group(1)}"
                f" (default {_literal(defaults[m.group(1)])}, threshold '{m.group(1)}').")
    return f" Rows are capped inside every window_days block by the body's LIMIT {limit}."


def model_entry(spec: QuerySpec, grains: dict[str, list[str]]) -> dict:
    body = runner_body(spec.body)
    entry: dict = {
        "name": model_name(spec),
        "description": spec.read_this + _limit_note(spec, body),
        "meta": {
            "query_id": spec.query_id,
            "title": spec.title,
            "domain": spec.domain,
            "tier": spec.tier,
            "stars": spec.stars,
            "origin": spec.origin,
            "windowed": spec.windowed,
            "is_finding": spec.is_finding,
            "empty_if": list(spec.empty_if),
            "reads": list(spec.reads),
            "requires": spec.requires,
            "params": [dict(p) for p in spec.params],
            "confidence": spec.confidence,
            "confidence_note": spec.confidence_note,
            "healthy": spec.healthy,
            "investigate_if": spec.investigate_if,
            "actions": list(spec.actions),
            "next": [dict(n) for n in spec.next],
            "caveats": spec.caveats,
            "sql_url": spec.sql_url,
            "order_by": extract_order_by(body),
        },
    }
    columns = [
        {
            "name": "window_days",
            "data_tests": [
                "not_null",
                {"accepted_values": {"arguments": {"values": list(WINDOW_VALUES), "quote": False}}},
            ],
        }
    ]
    if spec.is_finding:
        columns.append(
            {
                "name": "status",
                "data_tests": [{"accepted_values": {"arguments": {"values": list(STATUS_VALUES)}}}],
            }
        )
    entry["columns"] = columns
    if spec.query_id in grains:
        entry["data_tests"] = [
            {"unique_grain": {"arguments": {"columns": ["window_days"] + grains[spec.query_id]}}}
        ]
    return entry


def render_domain_yml(domain: str, specs: list[QuerySpec], *, grains: dict[str, list[str]] | None = None) -> str:
    """The per-domain schema file `_findings__<domain>.yml` for every model in `specs`."""
    grains = grains if grains is not None else load_grains()
    ordered = sorted((s for s in specs if s.domain == domain), key=lambda s: s.query_id)
    doc = {"version": 2, "models": [model_entry(s, grains) for s in ordered]}
    text = yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=100, allow_unicode=False)
    return (
        f"# {GENERATED_MARK} for domain '{domain}'. Do not edit; rerun the generator.\n" + text
    )


