def model_path(spec: QuerySpec, out_dir: Path) -> Path:
    return out_dir / spec.domain / f"{model_name(spec)}.sql"


def yml_path(domain: str, out_dir: Path) -> Path:
    return out_dir / domain / f"_findings__{domain}.yml"


def _rel(path: Path, out_dir: Path = FINDINGS_DIR) -> str:
    """Repo-relative when under the repo (the real run); relative to the output directory
    otherwise (tests generate into a temporary directory), so no absolute path is ever baked in."""
    for base in (ROOT, out_dir):
        try:
            return path.relative_to(base).as_posix()
        except ValueError:
            continue
    return path.as_posix()


def load_manifest(out_dir: Path) -> dict:
    path = out_dir / MANIFEST_NAME
    if not path.exists():
        return {"commit": None, "models": [], "skipped": [], "ymls": []}
    return json.loads(path.read_text(encoding="utf-8"))


def _manifest_model(spec: QuerySpec, out_dir: Path) -> dict:
    return {
        "query_id": spec.query_id,
        "domain": spec.domain,
        "model": model_name(spec),
        "path": _rel(model_path(spec, out_dir), out_dir),
        "origin": spec.origin,
        "windowed": spec.windowed,
        "is_finding": spec.is_finding,
        "tags": model_tags(spec),
    }


def build_manifest(
    existing: dict, scope: list[QuerySpec], registry: dict[str, QuerySpec], out_dir: Path, commit: str
) -> dict:
    """The manifest after this run: entries for ids outside `scope` are kept (re-described from
    the registry when the id still exists), entries for ids in scope are recomputed."""
    scope_ids = {s.query_id for s in scope}
    models: dict[str, dict] = {}
    skipped: dict[str, dict] = {}
    for m in existing.get("models", []):
        qid = m["query_id"]
        if qid in scope_ids or qid not in registry:
            continue
        spec = registry[qid]
        if spec.executable:
            models[qid] = _manifest_model(spec, out_dir)
    for s in existing.get("skipped", []):
        qid = s["query_id"]
        if qid in scope_ids or qid not in registry or qid in models:
            continue
        reason = skip_reason(registry[qid])
        if reason:
            skipped[qid] = {"query_id": qid, "domain": registry[qid].domain, "reason": reason}
    for spec in scope:
        reason = skip_reason(spec)
        if reason:
            skipped[spec.query_id] = {"query_id": spec.query_id, "domain": spec.domain, "reason": reason}
        else:
            models[spec.query_id] = _manifest_model(spec, out_dir)
    domains = sorted({m["domain"] for m in models.values()})
    return {
        "commit": commit,
        "models": [models[k] for k in sorted(models)],
        "skipped": [skipped[k] for k in sorted(skipped)],
        "ymls": [_rel(yml_path(d, out_dir), out_dir) for d in domains],
    }


def manifest_text(manifest: dict) -> str:
    return json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def _write(path: Path, text: str, force: bool) -> None:
    if path.exists() and not force:
        head = path.read_text(encoding="utf-8")[:400]
        if GENERATED_MARK not in head:
            raise GenerationError(
                f"{_rel(path)} exists and lacks the '{GENERATED_MARK}' marker; refusing to "
                "overwrite a hand-written file (use --force)"
            )
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes() == data and not force:
        return
    path.write_bytes(data)


def select_scope(registry: dict[str, QuerySpec], only: list[str] | None, domain: str | None) -> list[QuerySpec]:
    if only:
        unknown = [q for q in only if q not in registry]
        if unknown:
            raise GenerationError(f"unknown query id(s): {unknown}")
        return [registry[q] for q in only]
    if domain:
        specs = [s for s in registry.values() if s.domain == domain]
        if not specs:
            raise GenerationError(f"no query has domain {domain!r}")
        return specs
    return list(registry.values())


def _expected_files(
    manifest: dict, registry: dict[str, QuerySpec], out_dir: Path, commit: str,
    contract: dict[str, set[str]], grains: dict[str, list[str]],
) -> dict[Path, str]:
    """Every file the manifest implies, rendered: model files, domain ymls, the manifest."""
    expected: dict[Path, str] = {}
    by_domain: dict[str, list[QuerySpec]] = {}
    for m in manifest["models"]:
        spec = registry[m["query_id"]]
        expected[model_path(spec, out_dir)] = render_model(spec, lock_commit=commit, contract=contract)
        by_domain.setdefault(spec.domain, []).append(spec)
    for domain, specs in by_domain.items():
        expected[yml_path(domain, out_dir)] = render_domain_yml(domain, specs, grains=grains)
    expected[out_dir / MANIFEST_NAME] = manifest_text(manifest)
    return expected


def generate(
    only: list[str] | None = None,
    domain: str | None = None,
    *,
    force: bool = False,
    out_dir: Path = FINDINGS_DIR,
    grains_dir: Path = GRAINS_DIR,
    lock_path: Path = LOCK_PATH,
    sources_yml: Path = SOURCES_YML,
    registry: list[QuerySpec] | None = None,
) -> dict:
    """Render and write the models in scope, their domain ymls and the manifest. Returns
    {'models': [...ids written], 'skipped': [{query_id, reason}], 'ymls': [paths]}."""
    specs = registry if registry is not None else load_registry()
    reg = {s.query_id: s for s in specs}
    scope = select_scope(reg, only, domain)
    commit = load_lock_commit(lock_path)
    contract = load_source_contract(sources_yml)
    grains = load_grains(grains_dir)
    manifest = build_manifest(load_manifest(out_dir), scope, reg, out_dir, commit)
    written: list[str] = []
    touched_domains: set[str] = set()
    for spec in scope:
        if skip_reason(spec):
            continue
        _write(model_path(spec, out_dir), render_model(spec, lock_commit=commit, contract=contract), force)
        written.append(spec.query_id)
        touched_domains.add(spec.domain)
    for dom in sorted(touched_domains):
        dom_specs = [reg[m["query_id"]] for m in manifest["models"] if m["domain"] == dom]
        _write(yml_path(dom, out_dir), render_domain_yml(dom, dom_specs, grains=grains), force)
    _write(out_dir / MANIFEST_NAME, manifest_text(manifest), True)
    skipped_in_scope = [
        {"query_id": s.query_id, "reason": skip_reason(s)} for s in scope if skip_reason(s)
    ]
    return {
        "models": written,
        "skipped": skipped_in_scope,
        "ymls": [_rel(yml_path(d, out_dir), out_dir) for d in sorted(touched_domains)],
    }


def check(
    only: list[str] | None = None,
    domain: str | None = None,
    *,
    out_dir: Path = FINDINGS_DIR,
    grains_dir: Path = GRAINS_DIR,
    lock_path: Path = LOCK_PATH,
    sources_yml: Path = SOURCES_YML,
    registry: list[QuerySpec] | None = None,
) -> dict:
    """Compare what is on disk with what the generator would write. Returns
    {'ok': bool, 'stale': [...], 'missing': [...], 'extra': [...], 'models': n, 'skipped': [...]}.
    Unscoped: every model the manifest records (plus its ymls and the manifest itself) must be
    present and byte-identical, and no unrecorded .sql/.yml may sit under the findings dir.
    Scoped (--only/--domain): the same for the ids in scope and the ymls of their domains."""
    specs = registry if registry is not None else load_registry()
    reg = {s.query_id: s for s in specs}
    commit = load_lock_commit(lock_path)
    contract = load_source_contract(sources_yml)
    grains = load_grains(grains_dir)
    # the manifest on disk names WHICH ids were generated; every other field is re-derived from
    # the registry so a changed header (tags, is_finding, ...) shows up as a stale file
    manifest = build_manifest(load_manifest(out_dir), [], reg, out_dir, commit)
    manifest_ids = {m["query_id"] for m in manifest["models"]}

    stale: list[str] = []
    missing: list[str] = []
    extra: list[str] = []
    skipped: list[dict] = []
    expected: dict[Path, str] = {}

    if only or domain:
        scope = select_scope(reg, only, domain)
        scope_models = [s for s in scope if not skip_reason(s)]
        skipped = [{"query_id": s.query_id, "reason": skip_reason(s)} for s in scope if skip_reason(s)]
        for spec in scope_models:
            if spec.query_id not in manifest_ids:
                missing.append(_rel(model_path(spec, out_dir), out_dir) + " (never generated)")
            else:
                expected[model_path(spec, out_dir)] = render_model(spec, lock_commit=commit, contract=contract)
        # a domain yml must describe EVERY model recorded for that domain, not just the scope
        for dom in sorted({s.domain for s in scope_models}):
            dom_specs = [reg[m["query_id"]] for m in manifest["models"] if m["domain"] == dom]
            if dom_specs:
                expected[yml_path(dom, out_dir)] = render_domain_yml(dom, dom_specs, grains=grains)
        n_models = len(scope_models)
    else:
        expected = _expected_files(manifest, reg, out_dir, commit, contract, grains)
        skipped = [{"query_id": s["query_id"], "reason": s["reason"]} for s in manifest["skipped"]]
        n_models = len(manifest["models"])

    for path, text in expected.items():
        if not path.exists():
            missing.append(_rel(path, out_dir))
        elif path.read_bytes() != text.encode("utf-8"):
            stale.append(_rel(path, out_dir))

    known_paths = set()
    for m in manifest["models"]:
        known_paths.add(model_path(reg[m["query_id"]], out_dir))
    for dom in {m["domain"] for m in manifest["models"]}:
        known_paths.add(yml_path(dom, out_dir))
    if out_dir.exists():
        for path in sorted(out_dir.rglob("*")):
            if path.is_file() and path.suffix in (".sql", ".yml", ".yaml") and path not in known_paths:
                extra.append(_rel(path, out_dir))

    return {
        "ok": not (stale or missing or extra),
        "stale": stale,
        "missing": missing,
        "extra": extra,
        "models": n_models,
        "skipped": skipped,
    }


